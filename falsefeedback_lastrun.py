    thisExp.addData('picture_viewing.started', picture_viewing.tStart)
    picture_viewing.maxDuration = None
    # keep track of which components have finished
    picture_viewingComponents = picture_viewing.components
    for thisComponent in picture_viewing.components:
        thisComponent.tStart = None
        thisComponent.tStop = None
